package com.acme.parkshare.platform.payments.interfaces.rest;

import com.acme.parkshare.platform.payments.application.queries.GetTransactionsByOwnerIdQuery;
import com.acme.parkshare.platform.payments.application.queryservices.PaymentsQueryService;
import com.acme.parkshare.platform.payments.interfaces.rest.resources.PaymentTransactionResource;
import io.swagger.v3.oas.annotations.Operation;
import io.swagger.v3.oas.annotations.tags.Tag;
import org.springframework.http.ResponseEntity;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.RequestParam;
import org.springframework.web.bind.annotation.RestController;

import java.util.List;

import static org.springframework.http.MediaType.APPLICATION_JSON_VALUE;

@RestController
@RequestMapping(value = "/api/v1/payment-transactions", produces = APPLICATION_JSON_VALUE)
@Tag(name = "Payment Transactions", description = "Earnings generated by completed reservations")
public class PaymentTransactionsController {

    private final PaymentsQueryService queryService;

    public PaymentTransactionsController(PaymentsQueryService queryService) {
        this.queryService = queryService;
    }

    @GetMapping
    @Operation(summary = "Get the earnings of an owner (?ownerId=)")
    public ResponseEntity<List<PaymentTransactionResource>> getByOwner(@RequestParam Long ownerId) {
        return ResponseEntity.ok(queryService.handle(new GetTransactionsByOwnerIdQuery(ownerId)).stream()
                .map(t -> new PaymentTransactionResource(t.id(), t.ownerId(), t.reservationId(), t.driverName(),
                        t.garageName(), t.date(), t.durationMinutes(), t.amountReceived()))
                .toList());
    }
}
